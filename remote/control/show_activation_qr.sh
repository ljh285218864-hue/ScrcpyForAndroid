#!/usr/bin/env bash
# Print the one-time primary-device activation QR in a trusted SSH terminal.
# Never save or upload this QR to GitHub or a public chat.
set -euo pipefail
if [[ $EUID -ne 0 ]]; then echo "请使用 sudo"; exit 1; fi
if [[ ! -r /etc/screensync/registration.env ]]; then
  echo "未找到 ScreenSync 服务器配置"; exit 1
fi
if ! command -v qrencode >/dev/null; then
  echo "缺少 qrencode，请安装 sudo apt-get install qrencode"; exit 1
fi
if ! command -v curl >/dev/null; then echo "缺少 curl"; exit 1; fi
API_URL="$(printenv SCREENSYNC_API_URL || echo https://screensync.privyluxe.com:8443)"
if [[ "$API_URL" != https://* ]]; then echo "不能使用非 HTTPS 地址"; exit 1; fi
if ! curl --fail --silent --show-error --max-time 8 "$API_URL/health" >/dev/null; then
  echo "公开 HTTPS 尚未验证通过；不要扫码测试。"
  exit 1
fi
set -a
# Read only the root-owned configuration file generated by install_ubuntu.sh.
source /etc/screensync/registration.env
set +a
echo "首次开通：在主手机的 ScreenSync Beta4 中点击扫码开通。"
echo "请仅在可信终端展示，不要截图转发给陌生人。"
printf 'screensync://activate?code=%s' "$SCREENSYNC_BOOTSTRAP_CODE" |
    qrencode -t ANSIUTF8
